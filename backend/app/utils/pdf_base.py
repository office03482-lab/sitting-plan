# ── Header/footer canvas ─────────────────────────────────────────
class _PageChromeCanvas(canvas.Canvas):
    """Draws header and footer on every page. Used internally by ReportPdfBuilder."""

    def __init__(
        self,
        *args,
        header_drawer: Optional[Callable] = None,
        footer_text: str = FOOTER_TEXT,
        page_width: float = 0,
        page_height: float = 0,
        left_margin: float = DEFAULT_MARGIN,
        right_margin: float = DEFAULT_MARGIN,
        bottom_margin: float = DEFAULT_BOTTOM_MARGIN,
        **kwargs,
    ):
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict] = []
        self._header_drawer = header_drawer
        self._footer_text = footer_text
        self._pw = page_width
        self._ph = page_height
        self._lm = left_margin
        self._rm = right_margin
        self._bm = bottom_margin

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        page_count = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self._draw_page_chrome(page_count)
            super().showPage()
        super().save()

    def _draw_page_chrome(self, page_count: int):
        if self._header_drawer:
            self._header_drawer(self)
        # Footer line
        self.setStrokeColor(SLATE_300)
        self.setLineWidth(0.5)
        self.line(self._lm, self._bm - 6, self._pw - self._rm, self._bm - 6)
        # Footer text & page number
        self.setFillColor(SLATE_500)
        self.setFont("Helvetica", 7.5)
        self.drawString(self._lm, self._bm - 20, self._footer_text)
        ts = fmt_timestamp()
        self.drawString(self._lm, self._bm - 33, ts)
        self.drawRightString(
            self._pw - self._rm,
            self._bm - 20,
            f"Page {self._pageNumber} of {page_count}",
        )


# ── High-level builder ────────────────────────────────────────────
class ReportPdfBuilder:
    """Drop-in builder that creates a PDF with consistent chrome.

    Usage:
        builder = ReportPdfBuilder(buffer, pagesize=landscape(A4))
        builder.add_title("My Report")
        builder.add_subtitle("Institute Name")
        builder.add_section_heading("Details")
        builder.add_table(...)
        builder.build(header_context={...})
    """

    def __init__(
        self,
        buffer: BytesIO,
        pagesize=landscape(A4),
        left_margin: float = DEFAULT_MARGIN,
        right_margin: float = DEFAULT_MARGIN,
        top_margin: float = DEFAULT_TOP_MARGIN,
        bottom_margin: float = DEFAULT_BOTTOM_MARGIN,
        title: str = "",
        author: str = "Sitting Plan System",
        footer_text: str = FOOTER_TEXT,
        header_drawer: Optional[Callable] = None,
    ):
        self.buffer = buffer
        self.pw, self.ph = pagesize
        self.lm = left_margin
        self.rm = right_margin
        self.tm = top_margin
        self.bm = bottom_margin
        self.content_width = self.pw - self.lm - self.rm
        self.pagesize = pagesize
        self.footer_text = footer_text
        self._header_drawer = header_drawer

        self.doc = SimpleDocTemplate(
            buffer,
            pagesize=pagesize,
            leftMargin=left_margin,
            rightMargin=right_margin,
            topMargin=top_margin,
            bottomMargin=bottom_margin,
            title=title,
            author=author,
        )
        self.styles = build_shared_styles()
        self.elements: list = []

    def add_title(self, text: str) -> None:
        self.elements.append(Paragraph(safe_pdf_text(text), self.styles["title"]))

    def add_subtitle(self, text: str) -> None:
        self.elements.append(Paragraph(safe_pdf_text(text), self.styles["subtitle"]))

    def add_section_heading(self, text: str) -> None:
        self.elements.append(
            Paragraph(safe_pdf_text(text), self.styles["section_heading"])
        )

    def add_spacer(self, height: float = 0.15 * inch) -> None:
        self.elements.append(Spacer(1, height))

    def add_small_note(self, text: str) -> None:
        self.elements.append(Paragraph(safe_pdf_text(text), self.styles["small_note"]))

    def add_table(self, table: Table) -> None:
        self.elements.append(table)

    def add_keep_together(self, *items) -> None:
        """Wrap items in KeepTogether to prevent page breaks between them."""
        wrappable = []
        for item in items:
            if isinstance(item, list):
                wrappable.extend(item)
            else:
                wrappable.append(item)
        self.elements.append(KeepTogether(wrappable))

    def add_page_break(self) -> None:
        self.elements.append(PageBreak())

    def build(self, header_context: Optional[dict] = None) -> BytesIO:
        header_drawer = self._header_drawer
        if header_drawer and header_context:
            # Bind header context
            def _make_drawer(fn, ctx):
                def drawer(canv):
                    fn(canv, ctx)
                return drawer
            header_drawer = _make_drawer(header_drawer, header_context)

        self.doc.build(
            self.elements,
            canvasmaker=lambda *args, **kwargs: _PageChromeCanvas(
                *args,
                header_drawer=header_drawer,
                footer_text=self.footer_text,
                page_width=self.pw,
                page_height=self.ph,
                left_margin=self.lm,
                right_margin=self.rm,
                bottom_margin=self.bm,
                **kwargs,
            ),
        )
        self.buffer.seek(0)
        return self.buffer
