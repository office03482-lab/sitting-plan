# ── Text utilities ───────────────────────────────────────────────
def safe_text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, (dict, list)):
        try:
            return json.dumps(value, ensure_ascii=False)
        except (TypeError, ValueError):
            return str(value)
    return str(value)


def safe_pdf_text(value: Any) -> str:
    text = safe_text(value)
    text = text.replace("\x00", "")
    text = text.replace("\r", " ")
    lines = [escape(segment) for segment in text.split("\n")]
    return "<br/>".join(lines)


def fmt_timestamp(dt: Optional[datetime] = None) -> str:
    return (dt or datetime.now()).strftime("%d %b %Y, %I:%M %p")


def fmt_date_iso(dt: Optional[datetime] = None) -> str:
    return (dt or datetime.now()).strftime("%Y-%m-%d")


